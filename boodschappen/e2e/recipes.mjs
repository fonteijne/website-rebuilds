import { chromium } from "playwright";
import { mkdirSync, readdirSync } from "node:fs";
const BASE = process.env.BASE ?? "http://localhost:3100";
mkdirSync("e2e/out", { recursive: true });
const exe = readdirSync("/opt/pw-browsers").filter((d) => d.startsWith("chromium-")).map((d) => `/opt/pw-browsers/${d}/chrome-linux/chrome`)[0];
const browser = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
const cdp = await ctx.newCDPSession(page);
await cdp.send("WebAuthn.enable");
await cdp.send("WebAuthn.addVirtualAuthenticator", { options: { protocol: "ctap2", transport: "internal", hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
const ok = (c, m) => { console.log(c ? "PASS" : "FAIL", m); if (!c) process.exitCode = 1; };
await page.goto(BASE);
await page.waitForSelector("text=Eerste keer");
await page.fill('input[autocomplete="name"]', "Sam");
await page.click("text=Passkey aanmaken");
await page.waitForSelector("#new-item", { timeout: 15000 });
await page.fill("#new-item", "melk"); await page.keyboard.press("Enter");
await page.click("text=Recepten");
await page.waitForSelector("text=Nog geen recepten");
await page.click("text=+ Nieuw recept");
await page.fill('input[placeholder^="bv. Spaghetti"]', "Spaghetti bolognese");
await page.fill("textarea", "gehakt\npasta\n2x ui\nmelk\ntomatenblokjes");
await page.waitForTimeout(500);
await page.screenshot({ path: "e2e/out/10-recipe-form.png" });
await page.click("text=/Opslaan/");
await page.waitForSelector("text=Spaghetti bolognese");
await page.waitForTimeout(700);
await page.screenshot({ path: "e2e/out/11-recipes.png" });
ok(true, "recept opgeslagen");
await page.click("text=Zet op lijst");
await page.waitForSelector("text=/5 ingrediënten op de lijst/");
await page.waitForTimeout(1500);
await page.screenshot({ path: "e2e/out/12-added.png" });
const n = await page.locator("[data-flip-id^=i-]").count();
ok(n === 5, `5 items op lijst (melk gedeeld): ${n}`);
await page.click("role=tab[name=Recept]"); await page.waitForTimeout(900);
await page.screenshot({ path: "e2e/out/13-by-recipe.png" });
ok(await page.locator("text=Haal van lijst").count() === 1, "receptweergave toont groep");
await page.click("role=tab[name=Categorie]"); await page.waitForTimeout(600);
await page.click("text=Recepten"); await page.waitForTimeout(800);
await page.click("text=/Haal van lijst/");
await page.waitForSelector("text=/van de lijst gehaald/");
await page.waitForTimeout(1200);
const left = await page.locator("[data-flip-id^=i-]").allTextContents();
ok(left.length === 1 && /melk/i.test(left[0]), `alleen losse melk blijft: ${left.length}`);
await page.waitForSelector("text=Zet op lijst");
await page.click("text=Wis"); await page.click("text=Zeker?");
await page.waitForSelector("text=Nog geen recepten");
ok(true, "recept verwijderd");
await browser.close();
