import { chromium } from "playwright";
import { readdirSync } from "node:fs";
const exe = readdirSync("/opt/pw-browsers").filter((d) => d.startsWith("chromium-")).map((d) => `/opt/pw-browsers/${d}/chrome-linux/chrome`)[0];
const browser = await chromium.launch({ executablePath: exe, args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await cdp.send("WebAuthn.enable");
await cdp.send("WebAuthn.addVirtualAuthenticator", { options: { protocol: "ctap2", transport: "internal", hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
await page.goto("http://localhost:3100");
await page.fill('input[autocomplete="name"]', "Sam");
await page.click("text=Passkey aanmaken");
await page.waitForSelector("#new-item");
await page.evaluate(() => (window.__m = 1));
const t = (type, y) => cdp.send("Input.dispatchTouchEvent", { type, touchPoints: type === "touchEnd" ? [] : [{ x: 200, y }] });
await t("touchStart", 300);
for (let y = 300; y <= 520; y += 20) await t("touchMove", y);
await page.screenshot({ path: "e2e/out/20-pull.png" });
await t("touchEnd");
await page.waitForSelector("#new-item");
await page.waitForTimeout(500);
const m = await page.evaluate(() => window.__m);
console.log(m === undefined ? "PASS pull-to-refresh herlaadde" : "FAIL niet herladen");
await browser.close();
